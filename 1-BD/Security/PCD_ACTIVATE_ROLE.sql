CREATE OR REPLACE PROCEDURE PCD_ACTIVATE_ROLE(pRole VARCHAR2) AUTHID CURRENT_USER IS
    ROLE_PASSWORD VARCHAR2(500);
BEGIN

    ROLE_PASSWORD := FNC_GET_ROLE_PASSWORD;

    EXECUTE IMMEDIATE 'SET ROLE ' || pRole || ' IDENTIFIED BY ' || ROLE_PASSWORD;

EXCEPTION
    WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('Error activando el rol: ' || pRole);
    RAISE;
END PCD_ACTIVATE_ROLE;